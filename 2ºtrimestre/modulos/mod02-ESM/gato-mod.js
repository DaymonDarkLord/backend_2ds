export function BanhoGato(raca, tipoBanho)
{
    return `O gato da raça ${raca} tomou um banho de ${tipoBanho}.`
}
export function AlimentarGato(raca, tipoComida)
{
    return `O gato da raca ${raca} foi alimentado com ${tipoComida}.`
}
export function TosaGato(raca, tipoTosa)
{
    return `O gato da raca ${raca} foi tosado com ${tipoTosa}.`
}